import os
import gc
import h5py
import random
import signal
import subprocess
import numpy as np
import tensorflow as tf

from pycomet import config as cfg
from pathlib import Path


def kill_process():
    """Send terminating signal to job `pid`."""
    os.kill(os.getpid(), signal.SIGTERM)

def close_all_hdf5():
    """Close all opened hdf5 files."""
    for obj in gc.get_objects():        # Browse through all objects
        if isinstance(obj, h5py.File):  # Just HDF5 files
            try:
                obj.close()
            except:
                pass

def set_random_seed(seed=None):
    if seed is not None:
        random.seed(seed)
        np.random.seed(seed)
        os.environ["TF_DETERMINISTIC_OPS"] = "1"
        tf.random.set_seed(seed)
        os.environ['PYTHONHASHSEED'] = str(seed)

def set_gpu_memory():
    gpus = tf.config.list_physical_devices('GPU')
    for gpu in gpus:
        try:
            tf.config.experimental.set_memory_growth(gpu, True)
        except:
            pass

def set_num_threads(n):
    tf.config.threading.set_inter_op_parallelism_threads(n)
    tf.config.threading.set_intra_op_parallelism_threads(n)

def generate_init_mod_file(path=''):
    path = os.path.abspath(path)
    module = Path(path).stem
    file = open(path + '/__init__.py', 'w')
    file.write(
        f"# This file is autogenerated by '{cfg._NAME}'. Do not erase.\n"
    )
    for p in os.listdir(path):
        if not any([Path(p).stem.startswith(s) for s in ('_', '.')]) \
            and Path(p).suffix == '.py':
            file.write(f'from {module}.{Path(p).stem} import *\n')
    file.close()

def load_external_module(
    load_cmd='module load plato',
    shell='/bin/bash',
    env_keys=("PATH", "LD_LIBRARY_PATH")
):
    # Initialize process
    p = subprocess.Popen(
        [shell],
        stdin=subprocess.PIPE,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE
    )
    # Invoke command
    cmd = ' '.join([f'{load_cmd}'] + [f"&& echo ${k}" for k in env_keys])
    out, err = p.communicate(cmd.encode())
    # Decode output
    out = out.decode().split('\n')
    out = [i for i in out if i]
    out = out[-len(env_keys):]
    # Update environment
    for i, k in enumerate(env_keys):
        os.environ[k] = out[i]
    return os.environ

