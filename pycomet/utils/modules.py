def append_mod_dir(
  modules={}
):
  """
  Append module directories to `sys.path`.

  :param modules: A dictionary containing module name-path pairs.
  :type modules: dict
  :example:
    {
      "numpy": "<path-to-numpy-folder>",
      # Add more modules as needed
    }
  
  This function appends specified module directories to the `sys.path` list,
  allowing you to dynamically add paths for Python modules that may not be
  in the default search paths. It is particularly useful for importing custom
  or external modules located in non-standard directories.
  """
  for (name, path) in modules.items():
    if (importlib.util.find_spec(name) is None):
      try:
        sys.path.append(os.path.abspath(path))
      except:
        continue


def load_mod_from_path(
  name,
  path
):
  """
  Load a Python module from a specified file path.

  :param name: Name to assign to the loaded module.
  :type name: str

  :param path: File path to the Python module (including '__init__.py').
  :type path: str

  :return: Loaded module.
  :rtype: module

  Load a Python module from the given file path and assign it
  the specified name. Returns the loaded module.
  """
  spec = importlib.util.spec_from_file_location(name, path)
  module = importlib.util.module_from_spec(spec)
  sys.modules[name] = module
  spec.loader.exec_module(module)
  return module


def reload_mod(
  mod_names=[]
):
  """
  Reload Python modules by their names.

  :param mod_names: A list of module names to reload.
  :type mod_names: list of str

  :return: A list of reloaded modules.
  :rtype: list of module objects

  This function takes a list of module names and reloads the corresponding
  modules. If a module does not exist in `sys.modules`, it will be imported.
  Submodules are also reloaded if present. The reloaded modules are returned
  as a list.
  """
  mod_list = []
  for name in tf.nest.flatten(mod_names):
    if (name in sys.modules.keys()):
      # Reload module
      importlib.reload(sys.modules[name])
      # Reload submodules
      path_to_mod = sys.modules[name].__path__
      for (importer, submod, ispkg) in pkgutil.iter_modules(path_to_mod):
        if (not submod.startswith('__')):
          importlib.reload(sys.modules[name+'.'+submod])
      # Collect reloaded module
      mod_list.append(sys.modules[name])
    else:
      # Import module
      mod_list.append(importlib.import_module(name))
  return mod_list


def generate_init_mod_file(
  path=''
):
  """
  Generate an '__init__.py' file for a Python module if it does not exist.

  :param path: The directory path where the module is located.
  :type path: str

  This function creates an '__init__.py' file in the specified directory
  to transform it into a Python package. If the '__init__.py' file already
  exists, it is not overwritten.

  It also automatically imports all non-hidden ('_' or '.') Python files
  in the same directory as the package.
  """
  path = os.path.abspath(path)
  module = Path(path).stem
  file = open(path + '/__init__.py', 'w')
  file.write(
    f"# This file is autogenerated by '{_cfg.name}'. Do not erase.\n"
  )
  for p in os.listdir(path):
    c1 = (not any([Path(p).stem.startswith(s) for s in ('_', '.')]))
    c2 = (Path(p).suffix == '.py')
    if (c1 and c2):
      file.write(f'from {module}.{Path(p).stem} import *\n')
  file.close()


def load_external_module(
  load_cmd='module load plato',
  shell='/bin/bash',
  env_keys=("PATH", "LD_LIBRARY_PATH"),
  nb_threads=4
):
  """
  Load non-Python packages using the Unix 'modules' software
  and update environment variables.

  This function is designed to load external modules and update
  environmental variables, primarily for use in conjunction with
  running background jobs with external softwares.

  :param load_cmd: Unix module loading command.
  :type load_cmd: str
  :example: "module load <module-filename>"

  :param shell: The type of shell to execute the command.
  :type shell: str
  :example: "/bin/bash"

  :param env_keys: A list of environmental variables to update
                   after loading the module.
  :type env_keys: list of str

  :param nb_threads: The number of threads to be set for BLAS
                     calculations within the environment.
  :type nb_threads: int

  :return: A dictionary representing the updated environment
           variables after loading the module and setting
           the number of threads.
  :rtype: dict

  The function initializes a subprocess with the specified shell, executes
  the provided module loading command, and captures the output. It then
  extracts and updates the specified environmental variables. Additionally,
  it sets the number of threads for BLAS calculations in the environment.
  The updated environment is returned as a dictionary.
  """
  # Initialize process
  p = subprocess.Popen(
    [shell],
    stdin=subprocess.PIPE,
    stdout=subprocess.PIPE,
    stderr=subprocess.PIPE
  )
  # Invoke command
  cmd = ' '.join([f'{load_cmd}'] + [f"&& echo ${k}" for k in env_keys])
  out = p.communicate(cmd.encode())[0]
  # Decode output
  out = out.decode().split('\n')
  out = [i for i in out if i]
  out = out[-len(env_keys):]
  # Update environment
  env = copy.deepcopy(os.environ)
  for (i, k) in enumerate(env_keys):
    env[k] = out[i]
  env = set_cpu_threads_env(nb_threads, env)
  return env


def import_matplotlib():
  """
  Import the Matplotlib module using a specific style defined in
  the configuration file of this package.

  :return: A tuple containing the Matplotlib module and the pyplot submodule.
  :rtype: tuple (matplotlib, matplotlib.pyplot)
  """
  import matplotlib
  from matplotlib import pyplot
  pyplot.style.use(_cfg.mpl['style'])
  return matplotlib, pyplot
